import { Previewer } from 'pagedjs';
import type { PdfRenderJob } from './contracts';

type InstrumentablePreviewer = Previewer & {
  chunker?: { q?: { tick?: (callback: FrameRequestCallback) => unknown } };
};

export interface FrameRendererHooks {
  /** Runs before pagination. Use it for serializable-input-derived DOM changes. */
  readonly prepareSource?: (source: HTMLElement, job: PdfRenderJob) => void | Promise<void>;
  /** Runs on physical pages before the artifact is serialized. */
  readonly finalizePages?: (stage: HTMLElement, job: PdfRenderJob) => void | Promise<void>;
  readonly pageAnchor?: (page: HTMLElement, pageIndex: number) => string | undefined;
}

export interface FramePaginationResult {
  readonly pageCount: number;
  readonly paginationCss: string;
  readonly durationMs: number;
}

/** Runs the only Paged.js pass. This module must execute inside the renderer frame. */
export async function paginateInFrame(
  stage: HTMLElement,
  job: PdfRenderJob,
  hooks: FrameRendererHooks = {},
  reportProgress?: (pagesCompleted: number) => void
): Promise<FramePaginationResult> {
  const startedAt = performance.now();
  stage.replaceChildren();

  const source = document.createElement('article');
  source.innerHTML = job.html;
  await hooks.prepareSource?.(source, job);

  const existingPagedStyles = new Set(document.head.querySelectorAll('style[data-pagedjs-inserted-styles]'));
  const styleUrl = URL.createObjectURL(new Blob([job.css], { type: 'text/css' }));
  const previewer = new Previewer() as InstrumentablePreviewer;
  accelerateHiddenFrame(previewer);
  const progressTimer = reportProgress
    ? window.setInterval(() => reportProgress(stage.querySelectorAll('.pagedjs_page').length), 500)
    : undefined;

  try {
    await previewer.preview(source, [styleUrl], stage);
  } finally {
    if (progressTimer !== undefined) window.clearInterval(progressTimer);
    URL.revokeObjectURL(styleUrl);
  }

  const pageCount = stage.querySelectorAll('.pagedjs_page').length;
  if (pageCount === 0) throw new Error('PDF pagination produced no physical pages.');
  await hooks.finalizePages?.(stage, job);

  // Include only styles generated by this pass. This also makes direct frame
  // reuse safe, even though the default host disposes every frame after one job.
  const generatedCss = Array.from(document.head.querySelectorAll<HTMLStyleElement>('style[data-pagedjs-inserted-styles]'))
    .filter(style => !existingPagedStyles.has(style))
    .map(style => style.textContent ?? '');

  return Object.freeze({
    pageCount,
    paginationCss: [job.css, ...generatedCss, job.artifactCss].filter(Boolean).join('\n'),
    durationMs: Math.round(performance.now() - startedAt)
  });
}

/**
 * Paged.js 0.4.3 schedules chunks with requestAnimationFrame. Browsers may
 * heavily throttle an off-screen frame, so replace only its documented-shaped
 * queue tick when present. Absence is safe and future versions can ignore it.
 */
function accelerateHiddenFrame(previewer: InstrumentablePreviewer): void {
  const queue = previewer.chunker?.q;
  if (!queue) return;
  queue.tick = callback => scheduleTask(callback);
}

function scheduleTask(callback: FrameRequestCallback): void {
  if (typeof MessageChannel === 'undefined') {
    window.setTimeout(() => callback(performance.now()), 0);
    return;
  }
  const channel = new MessageChannel();
  channel.port1.onmessage = () => {
    channel.port1.close();
    channel.port2.close();
    callback(performance.now());
  };
  channel.port2.postMessage(undefined);
}

export function defaultPageAnchor(page: HTMLElement): string | undefined {
  const source = page.querySelector<HTMLElement>('[data-pdf-anchor], [data-ref], [data-split-from]');
  return source?.dataset.pdfAnchor
    ?? source?.getAttribute('data-ref')
    ?? source?.getAttribute('data-split-from')
    ?? undefined;
}
